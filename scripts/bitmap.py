GLYPHS: dict[str, tuple[str, ...]] = {}
for _ch, _rows in _SPEC.items():
    _r = _rows.split()
    assert all(len(x) == 5 for x in _r) and len(_r) in (7, 8, 9), _ch
    GLYPHS[_ch] = tuple(_r + ["....."] * (9 - len(_r)))

ROWS, COLS = 9, 5
CAP = 7  # rows from the top of a cap to the baseline


def glyph(ch: str) -> tuple[str, ...]:
    return GLYPHS.get(ch) or GLYPHS["?"]


def n(v: float) -> str:
    """Compact number for path data."""
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def width(s: str, c: float, track: float = 1) -> float:
    """Ink width of `s` at cell size `c` with `track` empty cells between glyphs."""
    return max(len(s) * (COLS + track) - track, 0) * c


def cells(s: str, x: float, y: float, c: float, track: float = 1):
    """Yield (x, y, w) for every horizontal run of lit pixels; `y` is the top of row 0."""
    adv = (COLS + track) * c
    for i, ch in enumerate(s):
        gx = x + i * adv
        for r, row in enumerate(glyph(ch)):
            k = 0
            while k < COLS:
                if row[k] == "#":
                    j = k
                    while j < COLS and row[j] == "#":
                        j += 1
                    yield gx + k * c, y + r * c, (j - k) * c
                    k = j
                else:
                    k += 1


def path(s: str, x: float, y: float, c: float, track: float = 1, anchor: str = "start") -> str:
    """Path data for `s`. anchor: start | end | middle, measured on the ink width."""
    if anchor != "start":
        w = width(s, c, track)
        x -= w if anchor == "end" else w / 2
    return "".join(f"M{n(px)} {n(py)}h{n(w)}v{n(c)}h{n(-w)}z" for px, py, w in cells(s, x, y, c, track))


def grain_paths(s: str, x: float, y: float, c: float, track: float = 1, buckets: int = 3) -> list[str]:
    """Split a display string into `buckets` paths of single pixels, so each can carry its own
    opacity: lit cells that flicker slightly, like phosphor."""
    out = [[] for _ in range(buckets)]
    for px, py, w in cells(s, x, y, c, track):
        k = 0
        while k * c < w - 1e-6:
            cx = px + k * c
            h = int(hashlib.md5(f"{cx:.1f},{py:.1f}".encode()).hexdigest()[:4], 16)
            b = 0 if h % 10 < 6 else 1 if h % 10 < 9 else 2
            out[b].append(f"M{n(cx)} {n(py)}h{n(c)}v{n(c)}h{n(-c)}z")
            k += 1
    return ["".join(b) for b in out]


def text(s: str, x: float, y: float, c: float, fill: str, track: float = 1, anchor: str = "start", extra: str = "") -> str:
    return f'<path d="{path(s, x, y, c, track, anchor)}" fill="{fill}"{extra}/>'


# palettes ------------------------------------------------------------------
# The page itself is the void: every SVG is transparent, so GitHub's own ground shows through.
# `ink` is the frontmost layer; d1-d3 step back one depth each; `signal` is the single accent.
DARK = dict(name="dark", ink="#E6E2D6", d1="#BDB9AE", d2="#8C8A83", d3="#55534E", signal="#FFB000", void="#0D1117")
LIGHT = dict(name="light", ink="#141414", d1="#3B3B3B", d2="#666666", d3="#A3A3A3", signal="#B25E00", void="#FFFFFF")
THEMES = (DARK, LIGHT)

MOTION_CSS = "@media (prefers-reduced-motion:reduce){*{animation:none!important}}"


def svg(w: float, h: float, body: str, title: str, desc: str = "", style: str = "", comment: str = "") -> str:
    d = f'<desc id="d">{desc}</desc>' if desc else ""
    lab = 't d' if desc else 't'
    st = f"<style>{style}{MOTION_CSS}</style>" if style else ""
    cm = f"\n<!-- {comment} -->" if comment else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 {n(w)} {n(h)}" '
            f'width="{n(w)}" height="{n(h)}" role="img" aria-labelledby="{lab}">{cm}\n'
            f'<title id="t">{title}</title>{d}{st}\n{body}\n</svg>\n')
